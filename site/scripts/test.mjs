import assert from 'node:assert/strict';
import W from '../worker/index.js';
const base='https://example.chatgpt.site';
let stored;
const env={BUCKET:{get:async()=>stored?{json:async()=>JSON.parse(stored)}:null,put:async(k,v)=>{stored=v}},BUPT_INGEST_SECRET:'local-test-only'};
const identity={'oai-authenticated-user-id':'owner'};
const get=(p,h={})=>W.fetch(new Request(base+p,{headers:h}),env);
const post=(p,payload,h={})=>W.fetch(new Request(base+p,{method:'POST',headers:h,body:JSON.stringify(payload)}),env);
const req=(method,params)=>({jsonrpc:'2.0',id:1,method,params});
const ingest=(x,token='local-test-only')=>post('/api/ingest',x,{authorization:'Bearer '+token});
assert.equal((await get('/')).status,401);
assert.equal((await get('/api/snapshot',{authorization:'Bearer local-test-only'})).status,401);
const initial=await get('/',identity);
assert.equal(initial.status,200);
const page=await initial.text();
for(const content of ['北邮学习台','尚未同步','学习资料','未读通知','Google Tasks'])assert.ok(page.includes(content));
assert.ok(!page.includes('id="assignments"')&&!page.includes('本学期作业记录'));
const initialStatus=await (await get('/api/snapshot',identity)).json();
assert.equal(initialStatus.lastWrite,null);
const found=await (await post('/mcp',req('tools/list'))).json();
assert.equal(found.result.tools.length,5);
const noauth=await (await post('/mcp',req('tools/call',{name:'sync_status'}))).json();
assert.equal(noauth.error.code,-32001);
const absent=await (await post('/mcp',req('tools/call',{name:'unread_feedback'}),identity)).json();
assert.equal(JSON.parse(absent.result.content[0].text).connected,false);
const snapshot={run:{at:'2026-11-21T17:00:00Z',status:'success',mode:'write',runUrl:'https://github.com/example-user/study-desk/actions/runs/42',tasks:{created:1,updated:0,unchanged:2}},currentCourses:[{id:"current-id",name:"Mock Course"}],notices:[{title:'Mock unread <script>',courseId:"current-id",unread:true,score:'97',detail:'Feedback <strong>escaped</strong>',url:'https://ucloud.bupt.edu.cn/?token=not-allowed'},{title:'Mock read',courseId:"current-id",unread:false},{title:'Old semester only',courseId:"previous-id",course:"Mock Course",unread:true},{title:"No source ID",course:"Mock Course",unread:true}],resources:[{materialId:"handout-1",title:'Mock handout',course:'Mock Course',url:'https://ucloud.bupt.edu.cn/#/example',contentText:"Text actual.\n"+"A".repeat(6200),contentComplete:true},{materialId:"index-2",title:"Metadata only",course:"Mock Course",url:"https://ucloud.bupt.edu.cn/#/file2"}]};
assert.equal((await ingest(snapshot,'bad')).status,401);
assert.equal((await ingest({...snapshot,run:{...snapshot.run,runUrl:'https://evil.invalid'}})).status,400);
assert.equal((await ingest(snapshot)).status,200);
const s=await (await get('/api/snapshot',identity)).json();
assert.equal(s.lastWrite.tasks.created,1);
assert.equal(s.notices.length,1);
assert.equal(s.notices[0].url,null);
assert.equal(s.notices[0].course,'Mock Course');
assert.ok(!JSON.stringify(s.resources).includes('Text actual.'));
const later=await (await get('/',identity)).text();
assert.ok(later.includes('Mock unread &lt;script&gt;')&&!later.includes('Mock read')&&!later.includes('Old semester only')&&later.includes('Mock handout'));
assert.match(later, /href="\/" aria-current="page"/);
assert.equal((await get('/notices')).status,401);
assert.equal((await get('/materials')).status,401);
assert.equal((await get('/wrong',identity)).status,404);
const noticePage=await (await get('/notices',identity)).text();
assert.match(noticePage, /href="\/notices" aria-current="page"/);
assert.match(noticePage, /仅当前课程/);
assert.ok(noticePage.includes('Mock unread &lt;script&gt;')&&!noticePage.includes('Mock handout')&&!noticePage.includes('Old semester only'));
const emptyNotices=await (await get('/notices?course=Missing',identity)).text();
assert.match(emptyNotices,/没有符合条件的结果/);
const materialPage=await (await get('/materials?q=handout&course=Mock%20Course',identity)).text();
assert.match(materialPage, /href="\/materials" aria-current="page"/);
assert.ok(materialPage.includes('Mock handout')&&!materialPage.includes('Mock unread')&&!materialPage.includes('Metadata only'));
assert.match(materialPage,/data-choice="Mock Course"[^>]+aria-current="true"/);
assert.match(later,/href="\/notices#notice-1"/);
assert.match(noticePage,/<details class="notice-detail">/);
assert.match(noticePage,/Feedback &lt;strong&gt;escaped&lt;\/strong&gt;/);
assert.doesNotMatch(noticePage,/token=not-allowed/);
assert.match(emptyNotices,/data-course="Mock Course" data-count="1" hidden/);
assert.match(materialPage,/阅读已收录的文字：Mock handout/);
assert.match(materialPage,/在云邮打开：Mock handout/);
assert.doesNotMatch(materialPage, /\sdownload(?:=|\s)/);
assert.equal((await get('/materials/read?id=handout-1')).status,401);
const reader=await (await get('/materials/read?id=handout-1',identity)).text();
assert.match(reader,/非原文件/);
assert.match(reader,/Text actual\./);
assert.equal((await get('/materials/read?id=index-2',identity)).status,302);
const injection=await (await get('/materials?q=%22%3E%3Cscript%3E',identity)).text();
assert.match(injection,/&quot;&gt;&lt;script&gt;/);
assert.doesNotMatch(injection,/<script>/);
const filter=await (await post('/mcp',req('tools/call',{name:'find_materials',arguments:{query:'handout'}}),identity)).json();
const results=JSON.parse(filter.result.content[0].text);
assert.equal(results.items.length,1);
assert.equal(results.items[0].contentStatus,"complete");
const read=async (name,args)=>JSON.parse((await (await post('/mcp',req('tools/call',{name,arguments:args}),identity)).json()).result.content[0].text);
const content=await read("read_material",{materialId:"handout-1"});
assert.ok(content.available&&content.text.startsWith("Text actual.\n")&&content.text.length===6000&&content.nextOffset===6000);
assert.equal((await read("read_material",{materialId:"handout-1",offset:6000})).nextOffset,null);
assert.equal((await read("read_material",{materialId:"index-2"})).available,false);
const unread=await read("unread_feedback",{});
assert.deepEqual(unread.items.map(x=>x.title),["Mock unread <script>"]);
assert.equal((await ingest({...snapshot,run:{...snapshot.run,at:'2026-11-21T16:50:00Z'}})).status,409);
assert.equal((await ingest({run:{...snapshot.run,mode:'dry_run',at:'2026-11-21T18:00:00Z'}})).status,200);
const after=await (await get('/api/snapshot',identity)).json();
assert.equal(after.lastWrite.tasks.created,1);
assert.equal(after.resources.length,2);
assert.equal(after.run.mode,'dry_run');
